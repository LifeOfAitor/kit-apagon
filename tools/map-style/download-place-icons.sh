#!/usr/bin/env bash
# Downloads the place icons of decision 0011 from a pinned commit of mapbox/maki (CC0-1.0, public
# domain) and converts them into Android vector drawables for feature/map. The assembly point icon
# is not in Maki; it is drawn by hand in place_icon_assembly_point.xml and is not touched here.
# The glyph is white; the app draws the coloured circle behind it.

set -euo pipefail

readonly MAKI_COMMIT="28e2a3602e4bde033a1dd388e86e9c117b425e34"
readonly MAKI_BASE_URL="https://raw.githubusercontent.com/mapbox/maki/${MAKI_COMMIT}/icons"
# Maki icon name and the place category of decision 0011 it represents.
readonly ICONS=(
    "pharmacy:pharmacy"
    "hospital:health_centre"
    "drinking-water:drinking_water"
    "defibrillator:defibrillator"
    "police:police"
    "fire-station:fire_station"
)

script_directory="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly OUTPUT_DIRECTORY="${script_directory}/../../feature/map/src/main/res/drawable"

convert_to_vector_drawable() {
    python3 -I -c '
import sys, xml.etree.ElementTree as ElementTree
svg = ElementTree.parse(sys.stdin).getroot()
paths = [element.get("d") for element in svg.iter() if element.tag.endswith("path")]
if len(paths) != 1:
    sys.exit("Expected exactly one path in the Maki icon")
path_data = " ".join(paths[0].split())
print("<?xml version=\"1.0\" encoding=\"utf-8\"?>")
print("<!-- Generated by tools/map-style/download-place-icons.sh from Maki (CC0-1.0). Do not edit. -->")
print("<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"")
print("    android:width=\"15dp\"")
print("    android:height=\"15dp\"")
print("    android:viewportWidth=\"15\"")
print("    android:viewportHeight=\"15\">")
print("    <path")
print("        android:fillColor=\"#FFFFFFFF\"")
print("        android:pathData=\"" + path_data + "\" />")
print("</vector>")
'
}

mkdir -p "$OUTPUT_DIRECTORY"
for icon in "${ICONS[@]}"; do
    maki_name="${icon%%:*}"
    category="${icon##*:}"
    curl --fail --silent --show-error --location "${MAKI_BASE_URL}/${maki_name}.svg" \
        | convert_to_vector_drawable > "${OUTPUT_DIRECTORY}/place_icon_${category}.xml"
done
echo "Place icons written to ${OUTPUT_DIRECTORY}"
